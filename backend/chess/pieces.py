"""Piece constants, values, glyphs and piece-square tables.

Squares are indexed 0..63 with a8 = 0, b8 = 1 ... h8 = 7, a7 = 8 ... h1 = 63.
White pieces are upper-case letters, black pieces are lower-case, '.' is empty.
"""

